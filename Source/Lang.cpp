Language get()
{
    int l = currentLanguage.load();
    if (l < 0)
    {
        // prima volta: scelta salvata, altrimenti la lingua del sistema
        juce::PropertiesFile props (settingsOptions());
        const auto systemIsItalian = juce::SystemStats::getUserLanguage().startsWithIgnoreCase ("it")
                                  || juce::SystemStats::getDisplayLanguage().startsWithIgnoreCase ("it");
        l = props.getIntValue ("language", systemIsItalian ? 0 : 1) == 1 ? 1 : 0;
        currentLanguage.store (l);
    }
    return (Language) l;
}

void set (Language lang)
{
    currentLanguage.store ((int) lang);
    juce::PropertiesFile props (settingsOptions());
    props.setValue ("language", (int) lang);
    props.saveIfNeeded();
}

juce::String translate (const juce::String& italian)
{
    if (get() == Language::Italian)
        return italian;

    const auto& t = englishTable();
    const auto it = t.find (italian);
    return it != t.end() ? it->second : italian;
}

